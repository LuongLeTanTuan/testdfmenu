#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
gen_skins.py
Generates PxSkinCatalog.h from D:/delta/_catalog.json for PxExtNoJB.
Provenance:
  Extracted from DeltaForceClient.app/Frameworks/PxExtFFi.framework/PxExtFFi
  Contains 85 weapon groups and 705 valid skins with uint32 IDs.
"""

import json
import os
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_DIR = os.path.abspath(os.path.join(SCRIPT_DIR, ".."))
CATALOG_PATH = os.path.abspath(os.path.join(PROJECT_DIR, "..", "_catalog.json"))
OUTPUT_HEADER = os.path.join(PROJECT_DIR, "Menu", "PxSkinCatalog.h")

def escape_c_string(s):
    # Escape double quotes and backslashes, handle UTF-8 cleanly
    out = []
    for c in s:
        if c == '\\':
            out.append('\\\\')
        elif c == '"':
            out.append('\\"')
        elif c == '\n':
            out.append('\\n')
        elif c == '\r':
            out.append('\\r')
        elif c == '\t':
            out.append('\\t')
        else:
            out.append(c)
    return "".join(out)

def main():
    if not os.path.exists(CATALOG_PATH):
        print(f"Error: Catalog not found at {CATALOG_PATH}")
        sys.exit(1)

    with open(CATALOG_PATH, "r", encoding="utf-8") as f:
        data = json.load(f)

    order = data.get("order", [])
    weapons = data.get("weapons", {})

    print(f"Loaded {len(order)} weapon groups from catalog.")

    total_skins = sum(len(weapons.get(w, [])) for w in order)
    print(f"Total skin entries: {total_skins}")

    lines = []
    lines.append("//")
    lines.append("// PxSkinCatalog.h")
    lines.append("// Auto-generated by tools/gen_skins.py from _catalog.json")
    lines.append("// Provenance: Extracted from vendor PxExtFFi binary (705 skins, 85 weapon groups)")
    lines.append("// DO NOT EDIT DIRECTLY")
    lines.append("//\n")
    lines.append("#ifndef PX_SKIN_CATALOG_H")
    lines.append("#define PX_SKIN_CATALOG_H\n")
    lines.append("#include <stdint.h>")
    lines.append("#include <stddef.h>\n")
    lines.append("#ifdef __cplusplus")
    lines.append('extern "C" {')
    lines.append("#endif\n")

    lines.append("typedef struct {")
    lines.append("    uint32_t weaponIndex;")
    lines.append("    uint32_t skinId;")
    lines.append("    const char *name;")
    lines.append("} PxSkinEntry;\n")

    # Weapons array
    lines.append(f"static const uint32_t kPxWeaponCount = {len(order)};")
    lines.append("static const char * const kPxWeaponNames[] = {")
    for w in order:
        lines.append(f'    "{escape_c_string(w)}",')
    lines.append("};\n")

    # Skins catalog array
    lines.append(f"static const uint32_t kPxSkinCount = {total_skins};")
    lines.append("static const PxSkinEntry kPxSkinCatalog[] = {")
    for w_idx, w in enumerate(order):
        w_skins = weapons.get(w, [])
        for s in w_skins:
            s_id = s.get("id", 0)
            s_name = s.get("name", "")
            lines.append(f'    {{ {w_idx}, 0x{s_id:08X}U, "{escape_c_string(s_name)}" }},')
    lines.append("};\n")

    # Helper lookup functions
    lines.append("static inline const char *pxWeaponNameAt(uint32_t weaponIdx) {")
    lines.append("    if (weaponIdx >= kPxWeaponCount) return \"\";")
    lines.append("    return kPxWeaponNames[weaponIdx];")
    lines.append("}\n")

    lines.append("static inline uint32_t pxSkinCountForWeapon(uint32_t weaponIdx) {")
    lines.append("    if (weaponIdx >= kPxWeaponCount) return 0;")
    lines.append("    uint32_t count = 0;")
    lines.append("    for (uint32_t i = 0; i < kPxSkinCount; i++) {")
    lines.append("        if (kPxSkinCatalog[i].weaponIndex == weaponIdx) count++;")
    lines.append("        else if (count > 0) break; // Catalog is grouped by weapon")
    lines.append("    }")
    lines.append("    return count;")
    lines.append("}\n")

    lines.append("static inline const PxSkinEntry *pxSkinForWeaponAt(uint32_t weaponIdx, uint32_t skinIndexInWeapon) {")
    lines.append("    if (weaponIdx >= kPxWeaponCount) return NULL;")
    lines.append("    uint32_t seen = 0;")
    lines.append("    for (uint32_t i = 0; i < kPxSkinCount; i++) {")
    lines.append("        if (kPxSkinCatalog[i].weaponIndex == weaponIdx) {")
    lines.append("            if (seen == skinIndexInWeapon) return &kPxSkinCatalog[i];")
    lines.append("            seen++;")
    lines.append("        } else if (seen > 0) {")
    lines.append("            break;")
    lines.append("        }")
    lines.append("    }")
    lines.append("    return NULL;")
    lines.append("}\n")

    lines.append("#ifdef __cplusplus")
    lines.append("}")
    lines.append("#endif\n")
    lines.append("#endif // PX_SKIN_CATALOG_H\n")

    os.makedirs(os.path.dirname(OUTPUT_HEADER), exist_ok=True)
    with open(OUTPUT_HEADER, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"Successfully generated {OUTPUT_HEADER} ({len(lines)} lines)")

if __name__ == "__main__":
    main()
